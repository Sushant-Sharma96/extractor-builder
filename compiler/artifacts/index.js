'use strict';

/**
 * Product artifact emission — adapts architecture EmitPlan / ResolvedIR / domain IRs
 * onto the existing figma-build emitter (analyze + emit). No second compiler.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const figmaBuild = require('../../server/figma-build');
const { packageSite } = require('../../server/package-site');
const { applyPlanToTree, cssVarName, toSourceId } = require('./apply-plan');
const { renderIrExperimental } = require('./ir-experimental-renderer');

function tokenCss(tokenIr) {
  const tokens = (tokenIr && tokenIr.payload && tokenIr.payload.tokens) || [];
  if (!tokens.length) return '';
  const lines = tokens
    .slice()
    .sort((a, b) => (a.tokenId < b.tokenId ? -1 : 1))
    .map((t) => {
      let val = t.value;
      if (typeof val === 'number') val = `${val}px`;
      else if (val == null) val = 'initial';
      else val = String(val);
      return `  ${cssVarName(t.tokenId)}: ${val};`;
    });
  return `/* --- design tokens (TokenIR) --- */\n:root {\n${lines.join('\n')}\n}\n`;
}

function responsiveCss(responsiveIr) {
  const payload = responsiveIr && responsiveIr.payload;
  if (!payload) return '';
  const bps = [...(payload.breakpoints || [])].sort((a, b) => {
    const wa = a.widthHint != null ? Number(a.widthHint) : 9999;
    const wb = b.widthHint != null ? Number(b.widthHint) : 9999;
    return wa - wb;
  });
  if (!bps.length && !(payload.adaptations || []).length) return '';

  const parts = ['/* --- responsive (ResponsiveIR) --- */'];
  const byBp = new Map();
  for (const a of payload.adaptations || []) {
    for (const bpId of a.atBreakpointIds || ['bp:default']) {
      if (!byBp.has(bpId)) byBp.set(bpId, []);
      byBp.get(bpId).push(a);
    }
  }

  for (const bp of bps) {
    const width = bp.widthHint != null ? Number(bp.widthHint) : null;
    const adaptations = byBp.get(bp.breakpointId) || [];
    const rules = [];
    for (const a of adaptations) {
      const src = toSourceId(a.nodeId);
      if (!src) continue;
      const sel = `[data-node="${src}"]`;
      if (a.strategy === 'stack' || a.layoutMode === 'VERTICAL') {
        rules.push(`  ${sel} { flex-direction: column; flex-wrap: nowrap; }`);
      } else if (a.strategy === 'wrap') {
        rules.push(`  ${sel} { flex-wrap: wrap; }`);
      } else if (a.strategy === 'hide') {
        rules.push(`  ${sel} { display: none !important; }`);
      } else if (a.strategy === 'shrink') {
        rules.push(`  ${sel} { max-width: 100%; }`);
      }
    }
    if (width != null && Number.isFinite(width)) {
      // Skip empty breakpoint stubs — noise with no effect
      if (!rules.length) continue;
      parts.push(`@media (max-width: ${Math.round(width)}px) {\n${rules.join('\n')}\n}`);
    } else if (rules.length) {
      parts.push(`/* ${bp.breakpointId} */\n${rules.join('\n')}`);
    }
  }

  // Mark nodes for responsive selectors
  if (parts.length <= 1) return '';
  return parts.join('\n\n') + '\n';
}

function stampDataNodeIds(tree) {
  if (!tree) return;
  if (tree.nodeId != null) {
    if (!tree.attrs) tree.attrs = {};
    if (!tree.attrs['data-node']) tree.attrs['data-node'] = String(tree.nodeId);
  }
  for (const c of tree.children || []) stampDataNodeIds(c);
}

function buildJs(emitPlan, a11yIr) {
  const payload = emitPlan && (emitPlan.payload || emitPlan);
  const modules = (payload && payload.jsModules) || [];
  const lines = [
    '// script.js — generated by architecture compile() → product emitter adapter',
    '// static design baseline; authorized modules listed below',
  ];
  if (modules.length) {
    lines.push('const authorizedModules = ' + JSON.stringify(modules.map((m) => m.moduleId)) + ';');
    lines.push('void authorizedModules;');
  } else {
    lines.push('// no authorized behavior modules');
  }

  const focus = (a11yIr && a11yIr.payload && a11yIr.payload.focusOrder) || [];
  if (focus.length) {
    lines.push('');
    lines.push('// AccessibilityIR focus order (lightweight keyboard assist)');
    lines.push('(function () {');
    lines.push('  document.addEventListener("keydown", function (e) {');
    lines.push('    if (e.key !== "Tab") return;');
    lines.push('    // browser handles tabindex from AccessibilityIR overlays');
    lines.push('  });');
    lines.push('})();');
  } else {
    lines.push('// no runtime interactivity');
  }
  return lines.join('\n') + '\n';
}

function loadIrFromWorkspace(workspace, fingerprint) {
  const get = (id) => (id && workspace ? workspace.getIrSlice(id) : null);
  return {
    tokenIr: get(fingerprint.tokenSliceId),
    semanticIr: get(fingerprint.semanticSliceId),
    responsiveIr: get(fingerprint.responsiveSliceId),
    accessibilityIr: get(fingerprint.accessibilitySliceId),
    componentIr: get(fingerprint.componentSliceId),
    resolvedIr: get(fingerprint.resolvedSliceId),
    emitPlan: get(fingerprint.emitPlanSliceId),
  };
}

/** Bump when figma-build emit / layout recovery / emitMode changes — busts .compile-cache.json. */
const EMIT_ADAPTER_VERSION = 'emit-modes-v39-articles-outer-align';

function artifactFingerprint(fp, emitMode) {
  const key = [
    EMIT_ADAPTER_VERSION,
    normalizeEmitModeForCache(emitMode),
    fp && fp.emitPlanChecksum,
    fp && fp.resolvedIrChecksum,
    fp && fp.tokenIrChecksum,
    fp && fp.semanticIrChecksum,
    fp && fp.responsiveIrChecksum,
    fp && fp.accessibilityIrChecksum,
    fp && fp.componentIrChecksum,
    fp && fp.ndgChecksum,
  ].join('|');
  return crypto.createHash('sha256').update(key || 'empty').digest('hex').slice(0, 24);
}

function normalizeEmitModeForCache(mode) {
  const m = String(mode == null || mode === '' ? 'auto' : mode).toLowerCase().trim();
  if (m === 'pixel' || m === 'preview' || m === 'pixel-preview') return 'pixel';
  if (m === 'standard' || m === 'production' || m === 'layout-standard') return 'standard';
  return 'auto'; // dual-path product default
}

/**
 * legacy and ir-experimental deliberately use renderer-distinct cache fingerprints
 * (see `emitArtifactsIrExperimental()`'s doc comment) so neither ever returns the
 * other's cached artifact as a false HIT. That does NOT stop either renderer from
 * unconditionally overwriting an outDir the other renderer just wrote to — from
 * either renderer's own point of view, a fingerprint mismatch just looks like an
 * ordinary cache miss. Side-by-side renderer comparison on the same outDir is a
 * documented, intentional use of this toggle — so this does not block the write —
 * but it must never happen silently. Callers can inspect `rendererSwitchedFrom` on
 * the result to detect it.
 */
function readPriorRenderer(outDir) {
  try {
    const metaPath = path.join(outDir, '.compile-cache.json');
    if (!fs.existsSync(metaPath)) return null;
    const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
    // Caches written before this field existed are all legacy (ir-experimental has
    // stamped `renderer` since its cache file was introduced).
    return meta.renderer || 'legacy';
  } catch (_) {
    return null;
  }
}

function warnIfRendererSwitch(outDir, nextRenderer) {
  const prior = outDir ? readPriorRenderer(outDir) : null;
  if (prior && prior !== nextRenderer) {
    console.warn(
      `[emitArtifacts] renderer switch on shared outDir ${outDir}: previous output was ` +
      `'${prior}', this compile is '${nextRenderer}' — overwriting existing index.html/styles.css.`
    );
  }
  return prior && prior !== nextRenderer ? prior : null;
}

/**
 * Emit browser-ready artifacts by reusing server/figma-build.
 *
 * @param {object} opts
 * @param {object} opts.document — raw Figma-like document
 * @param {object} opts.fingerprint
 * @param {object} [opts.workspace]
 * @param {object} [opts.emitPlan] — IrSlice or payload
 * @param {object} [opts.irs] — preloaded domain IR slices
 * @param {string} [opts.outDir]
 * @param {string} [opts.title]
 * @param {object} [opts.imageUrls]
 * @param {object} [opts.imageFillUrls]
 * @param {object} [opts.svgMarkup]
 * @param {string[]} [opts.fonts]
 * @param {string} [opts.slug]
 * @param {string} [opts.url]
 * @param {object} [opts.localByUrl]
 * @param {boolean} [opts.downloadImages]
 * @param {string} [opts.emitMode] — 'auto' | 'pixel' | 'standard' (default auto) — a
 *   LEGACY-internal concept that only tunes `server/figma-build.js`'s own analyze/emit
 *   behavior; it does NOT choose between the legacy emitter and the new IR renderer.
 * @param {boolean} [opts.useCache]
 * @param {string} [opts.renderer] — Phase 5 (docs/COMPILER_MIGRATION_BLUEPRINT.md,
 *   NARROWED per explicit user decision: toggle only, no default flip, no deletions) —
 *   `'legacy'` (default, and what every existing caller gets when this is omitted —
 *   behavior is byte-identical to before this flag existed: `server/figma-build.js`'s
 *   `analyze()`+`emit()`) or `'ir-experimental'` (routes through the new NDG -> geometry/
 *   component/layout/responsive detection -> `materializeHtml()` pipeline via
 *   `./ir-experimental-renderer.js`). DIAGNOSTIC / OPT-IN ONLY — `'ir-experimental'` does
 *   NOT yet match legacy's HTML/CSS byte-for-byte (see Phase 3/4 STATUS notes in the
 *   blueprint for the documented, architecturally-blocked gaps: constraint-transcriber
 *   custom properties, legacy's heuristic-derived class names, per-run text overrides).
 *   Use it only for side-by-side comparison while validating the new renderer on real
 *   projects — never wire it into a default/serving path without re-reading those notes.
 */
async function emitArtifacts(opts = {}) {
  const t0 = Date.now();
  if (!opts.document) {
    throw new Error('emitArtifacts requires document');
  }

  const renderer = opts.renderer === 'ir-experimental' ? 'ir-experimental' : 'legacy';

  if (renderer === 'ir-experimental') {
    return emitArtifactsIrExperimental(opts);
  }

  const emitMode = normalizeEmitModeForCache(opts.emitMode);
  const fingerprint = opts.fingerprint || {};
  const artFp = artifactFingerprint(fingerprint, emitMode);
  const outDir = opts.outDir || null;

  if (opts.useCache !== false && outDir) {
    const metaPath = path.join(outDir, '.compile-cache.json');
    if (fs.existsSync(metaPath) && fs.existsSync(path.join(outDir, 'index.html'))) {
      try {
        const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
        if (meta.artifactFingerprint === artFp) {
          return {
            ok: true,
            cached: true,
            artifactFingerprint: artFp,
            dir: outDir,
            paths: {
              html: path.join(outDir, 'index.html'),
              css: path.join(outDir, 'styles.css'),
              js: path.join(outDir, 'script.js'),
              assets: path.join(outDir, 'assets'),
            },
            html: fs.readFileSync(path.join(outDir, 'index.html'), 'utf8'),
            css: fs.readFileSync(path.join(outDir, 'styles.css'), 'utf8'),
            js: fs.readFileSync(path.join(outDir, 'script.js'), 'utf8'),
            timings: { emitMs: Date.now() - t0 },
            summary: { cached: true, artifactFingerprint: artFp, emitMode },
            layoutReport: meta.layoutReport || null,
            emitMode,
          };
        }
      } catch (_) { /* miss */ }
    }
  }

  const rendererSwitchedFrom = warnIfRendererSwitch(outDir, 'legacy');

  const irs = {
    ...loadIrFromWorkspace(opts.workspace, fingerprint),
    ...(opts.irs || {}),
  };
  if (opts.emitPlan) irs.emitPlan = opts.emitPlan;

  const analyzed = figmaBuild.analyze(opts.document, { emitMode });
  applyPlanToTree(analyzed.tree, irs);
  stampDataNodeIds(analyzed.tree);
  figmaBuild.polishGeneratedTree(analyzed.tree);

  const fonts = opts.fonts || analyzed.fonts || [];
  const emitted = figmaBuild.emit(analyzed.tree, {
    imageUrls: opts.imageUrls || {},
    imageFillUrls: opts.imageFillUrls || {},
    svgMarkup: opts.svgMarkup || {},
    title: opts.title || 'Compiled design',
    fonts,
  });

  const css = [
    tokenCss(irs.tokenIr),
    emitted.css,
    responsiveCss(irs.responsiveIr),
  ].filter(Boolean).join('\n');

  const js = buildJs(irs.emitPlan, irs.accessibilityIr);
  const html = emitted.html;
  const result = {
    html,
    css,
    js,
    sections: emitted.sections,
    sectionsSummary: emitted.sectionsSummary,
  };

  let pkg = null;
  let paths = null;

  if (outDir) {
    const slug = opts.slug || path.basename(outDir);
    const parent = path.dirname(outDir);
    const assetSet = new Set();
    (html + '\n' + css).replace(/url\("?([^")]+)"?\)|src="([^"]+)"/g, (m, a1, b1) => {
      const u = a1 || b1;
      if (/^https?:/.test(u)) assetSet.add(u);
      return m;
    });
    const model = {
      url: opts.url || `compile://${slug}`,
      slug,
      title: opts.title || slug,
      assets: opts.assets || [...assetSet],
    };
    pkg = await packageSite(model, result, {
      outRoot: parent,
      downloadImages: opts.downloadImages !== false,
      localByUrl: opts.localByUrl || null,
    });
    // packageSite writes to parent/slug — if outDir differs, ensure files at outDir
    if (path.resolve(pkg.dir) !== path.resolve(outDir)) {
      fs.mkdirSync(outDir, { recursive: true });
      for (const f of ['index.html', 'styles.css', 'script.js', 'README.md']) {
        const src = path.join(pkg.dir, f);
        if (fs.existsSync(src)) fs.copyFileSync(src, path.join(outDir, f));
      }
      const assetsSrc = path.join(pkg.dir, 'assets');
      if (fs.existsSync(assetsSrc)) {
        const assetsDst = path.join(outDir, 'assets');
        fs.mkdirSync(assetsDst, { recursive: true });
        for (const name of fs.readdirSync(assetsSrc)) {
          fs.copyFileSync(path.join(assetsSrc, name), path.join(assetsDst, name));
        }
      }
    }
    fs.writeFileSync(
      path.join(outDir, '.compile-cache.json'),
      JSON.stringify({
        artifactFingerprint: artFp,
        renderer: 'legacy',
        emitMode,
        layoutReport: analyzed.layoutReport || null,
        emitPlanChecksum: fingerprint.emitPlanChecksum || null,
        at: new Date().toISOString(),
      }, null, 2)
    );
    paths = {
      html: path.join(outDir, 'index.html'),
      css: path.join(outDir, 'styles.css'),
      js: path.join(outDir, 'script.js'),
      assets: path.join(outDir, 'assets'),
      dir: outDir,
    };
  }

  const emitMs = Date.now() - t0;
  return {
    ok: true,
    cached: false,
    artifactFingerprint: artFp,
    renderer: 'legacy',
    rendererSwitchedFrom,
    html,
    css,
    js,
    sections: result.sections,
    sectionsSummary: result.sectionsSummary,
    fonts,
    analyzed: {
      imageNodeIds: analyzed.imageNodeIds,
      svgNodeIds: analyzed.svgNodeIds,
      fontCount: fonts.length,
    },
    emitMode,
    layoutReport: analyzed.layoutReport || null,
    dir: outDir || (pkg && pkg.dir) || null,
    paths,
    package: pkg,
    timings: { emitMs },
    summary: {
      cached: false,
      artifactFingerprint: artFp,
      emitMode,
      rendererSwitchedFrom,
      hasTokenCss: Boolean(tokenCss(irs.tokenIr)),
      hasResponsiveCss: Boolean(responsiveCss(irs.responsiveIr)),
      sections: (result.sections || []).length,
      htmlBytes: Buffer.byteLength(html, 'utf8'),
      cssBytes: Buffer.byteLength(css, 'utf8'),
      jsBytes: Buffer.byteLength(js, 'utf8'),
      layoutWarnings: ((analyzed.layoutReport && analyzed.layoutReport.warnings) || []).length,
    },
  };
}

/**
 * Phase 5 (NARROWED — toggle only) — `emitArtifacts({ renderer: 'ir-experimental' })`
 * branch. Never called unless a caller explicitly opts in (see `emitArtifacts()`'s
 * `opts.renderer` doc comment). Matches the shape of `emitArtifacts()`'s normal-path
 * return object as closely as makes sense for a diagnostic renderer that does not
 * produce `figmaBuild`-specific fields (`analyzed`, `layoutReport`, `emitMode`
 * semantics, on-disk caching) — those fields are present but set to inert/empty
 * defaults rather than omitted, so opt-in callers don't need special-case shape
 * handling beyond passing the flag, per the task's own requirement.
 *
 * No on-disk `.compile-cache.json` READ here — deliberate: that cache is keyed by
 * `artifactFingerprint(fingerprint, emitMode)`, which has no `renderer` component
 * (kept that way so the legacy path's cache key, and therefore its behavior, is
 * provably unchanged by this flag's addition — see `artifactFingerprint()`'s doc).
 * Reusing it here as a cache-HIT source without a renderer-aware key would risk a
 * legacy/ir-experimental cache collision on a shared `outDir`; simplest safe answer
 * for a diagnostic path is to always re-render fresh rather than trust it. It IS
 * still WRITTEN below (tagged `renderer: 'ir-experimental'`) so a later legacy
 * compile on the same `outDir` can detect the switch via `warnIfRendererSwitch()`
 * instead of silently overwriting this output with no trace of what happened.
 */
async function emitArtifactsIrExperimental(opts = {}) {
  const t0 = Date.now();
  const rendered = await renderIrExperimental(opts.document, {
    graphId: opts.graphId,
    title: opts.title,
    imageUrls: opts.imageUrls || {},
    imageFillUrls: opts.imageFillUrls || {},
    svgMarkup: opts.svgMarkup || {},
  });
  const { html, css } = rendered;
  const js = '// script.js — ir-experimental renderer (diagnostic/opt-in) — no authorized behavior modules\n';
  const artFp = `${artifactFingerprint(opts.fingerprint || {}, 'ir-experimental')}:ir-experimental`;
  const outDir = opts.outDir || null;
  const rendererSwitchedFrom = warnIfRendererSwitch(outDir, 'ir-experimental');

  let pkg = null;
  let paths = null;
  if (outDir) {
    const slug = opts.slug || path.basename(outDir);
    const parent = path.dirname(outDir);
    // packageSite() only downloads URLs listed in `model.assets` — it does not
    // scan the rendered html/css for them. renderIrExperimental() embeds
    // resolved imageFillUrls/imageUrls values directly as <img src>, so those
    // resolved URLs must also be surfaced here or every image silently falls
    // back to the branded placeholder (`data-asset-fallback`) regardless of
    // whether resolution/rendering/network all succeeded.
    const resolvedImageUrls = [
      ...Object.values(opts.imageFillUrls || {}),
      ...Object.values(opts.imageUrls || {}),
    ];
    const model = {
      url: opts.url || `compile://${slug}`,
      slug,
      title: opts.title || slug,
      assets: [...(opts.assets || []), ...resolvedImageUrls],
    };
    pkg = await packageSite(model, { html, css, js }, {
      outRoot: parent,
      downloadImages: opts.downloadImages !== false,
      localByUrl: opts.localByUrl || null,
    });
    if (path.resolve(pkg.dir) !== path.resolve(outDir)) {
      fs.mkdirSync(outDir, { recursive: true });
      for (const f of ['index.html', 'styles.css', 'script.js', 'README.md']) {
        const src = path.join(pkg.dir, f);
        if (fs.existsSync(src)) fs.copyFileSync(src, path.join(outDir, f));
      }
      const assetsSrc = path.join(pkg.dir, 'assets');
      if (fs.existsSync(assetsSrc)) {
        const assetsDst = path.join(outDir, 'assets');
        fs.mkdirSync(assetsDst, { recursive: true });
        for (const name of fs.readdirSync(assetsSrc)) {
          fs.copyFileSync(path.join(assetsSrc, name), path.join(assetsDst, name));
        }
      }
    }
    fs.writeFileSync(
      path.join(outDir, '.compile-cache.json'),
      JSON.stringify({
        artifactFingerprint: artFp,
        renderer: 'ir-experimental',
        at: new Date().toISOString(),
      }, null, 2)
    );
    paths = {
      html: path.join(outDir, 'index.html'),
      css: path.join(outDir, 'styles.css'),
      js: path.join(outDir, 'script.js'),
      assets: path.join(outDir, 'assets'),
      dir: outDir,
    };
  }

  const emitMs = Date.now() - t0;
  return {
    ok: true,
    cached: false,
    artifactFingerprint: artFp,
    html,
    css,
    js,
    sections: [],
    sectionsSummary: null,
    fonts: [],
    analyzed: {
      imageNodeIds: [],
      svgNodeIds: [],
      fontCount: 0,
    },
    emitMode: 'ir-experimental',
    renderer: 'ir-experimental',
    rendererSwitchedFrom,
    layoutReport: null,
    dir: outDir || (pkg && pkg.dir) || null,
    paths,
    package: pkg,
    timings: { emitMs },
    summary: {
      cached: false,
      artifactFingerprint: artFp,
      emitMode: 'ir-experimental',
      renderer: 'ir-experimental',
      rendererSwitchedFrom,
      hasTokenCss: false,
      hasResponsiveCss: /@media/.test(css),
      sections: 0,
      htmlBytes: Buffer.byteLength(html, 'utf8'),
      cssBytes: Buffer.byteLength(css, 'utf8'),
      jsBytes: Buffer.byteLength(js, 'utf8'),
      layoutWarnings: 0,
      nodeCount: rendered.nodeCount,
    },
  };
}

