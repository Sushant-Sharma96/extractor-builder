#!/usr/bin/env node
'use strict';

/**
 * Row-set renderer wiring — real-fixture validation.
 *
 * Read-only diagnostic (mirrors scripts/validate-row-set-challenge-arena.js's
 * pattern): loads the REAL cached Challenge Arena Figma document, calls
 * `renderIrExperimental()` (the `renderer: 'ir-experimental'` opt-in path,
 * compiler/artifacts/ir-experimental-renderer.js) end-to-end, and prints the
 * literal generated CSS rule for the row-set container's rows plus a sample
 * pass-through wrapper / chrome-hidden rule, so the row-set wiring added to
 * the renderer can be confirmed against real generated bytes (not asserted).
 *
 * Usage: node scripts/validate-row-set-render.js
 */

const path = require('path');
const fs = require('fs');

const { renderIrExperimental } = require('../compiler/artifacts/ir-experimental-renderer');

function findNode(n, id) {
  if (!n) return null;
  if (n.id === id) return n;
  for (const c of n.children || []) {
    const r = findNode(c, id);
    if (r) return r;
  }
  return null;
}

async function main() {
  const cacheDir = path.join(__dirname, '..', 'output', 'figma-cache', 'c0kt3mp76RoEiq3CFoeCHa__1_2');
  const doc = JSON.parse(fs.readFileSync(path.join(cacheDir, 'document.json'), 'utf8'));
  const full = doc.document || doc;
  const arena = findNode(full, '1:4');
  if (!arena) throw new Error('Node 1:4 Challenge Arena not found in cache');

  const { html, css } = await renderIrExperimental(arena, {
    graphId: 'g-validate-row-set-render',
    title: 'Challenge Arena row-set render validation',
  });

  fs.writeFileSync(path.join(__dirname, '..', 'output', 'row-set-render.html'), html);
  fs.writeFileSync(path.join(__dirname, '..', 'output', 'row-set-render.css'), css);

  const gridRules = [...css.matchAll(/\.([a-z0-9-]+)\s*\{\n([^}]*)\}/g)]
    .filter(([, , body]) => /display:\s*grid/.test(body) && /grid-template-columns/.test(body));
  const contentsRules = [...css.matchAll(/\.([a-z0-9-]+)\s*\{\n([^}]*)\}/g)]
    .filter(([, , body]) => /display:\s*contents/.test(body));
  const noneRules = [...css.matchAll(/\.([a-z0-9-]+)\s*\{\n([^}]*)\}/g)]
    .filter(([, , body]) => /display:\s*none/.test(body));

  console.log('=== Row-set renderer wiring — REAL Challenge Arena render ===');
  console.log('grid-template-columns rules found:', gridRules.length);
  for (const [full1, name, body] of gridRules) {
    console.log(`\n.${name} {\n${body}}`);
  }
  console.log('\ndisplay:contents rules found:', contentsRules.length);
  for (const [full1, name, body] of contentsRules) {
    console.log(`\n.${name} {\n${body}}`);
  }
  console.log('\ndisplay:none rules found:', noneRules.length);
  for (const [full1, name, body] of noneRules.slice(0, 3)) {
    console.log(`\n.${name} {\n${body}}`);
  }
}

main().catch((e) => {
  console.error('[validate-row-set-render] FATAL', e);
  process.exit(1);
});
